#!/usr/bin/env node
// Generate the bundled plain-text privacy policy shown on the Android launch consent dialog.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = process.argv[2] || path.join(root, 'docs/legal/privacy-source-v2.9.md');
const markdown = fs.readFileSync(sourcePath, 'utf8').replace(/^\uFEFF/, '');

function plain(markdownText) {
  return markdownText
    .replace(/```[\s\S]*?```/g, (block) => block.replace(/^```[^\n]*\n?|```$/g, ''))
    .replace(/!\[([^\]]*)\]\([^)]+\)/g, '$1')
    .replace(/\[([^\]]+)\]\((https?:[^)]+)\)/g, '$1（$2）')
    .replace(/\[([^\]]+)\]\(#[^)]+\)/g, '$1')
    .replace(/^\s*#+\s*/gm, '')
    .replace(/^\s*>\s?/gm, '')
    .replace(/^\s*[-*+]\s+/gm, '• ')
    .replace(/^\s*\d+[.)、]\s*/gm, (match) => `${match.trim()} `)
    .replace(/^\|[\s|:-]+\|\s*$/gm, '')
    .replace(/^\|(.+)\|\s*$/gm, (_match, row) => row.split('|').map((cell) => cell.trim()).filter(Boolean).join('  |  '))
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/__([^_]+)__/g, '$1')
    .replace(/\*([^*]+)\*/g, '$1')
    .replace(/_([^_]+)_/g, '$1')
    .replace(/~~([^~]+)~~/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/\\([#>|])/g, '$1')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

const text = plain(markdown);
const fingerprint = crypto.createHash('sha256').update(markdown).digest('hex');
const lines = text.split('\n').map((line) => JSON.stringify(`${line}\n`)).join(' +\n  ');
const generated =
  '// Generated by scripts/generate-app-privacy-policy-content.mjs; do not edit by hand.\n' +
  `// Source SHA-256: ${fingerprint}\n` +
  `export const APP_PRIVACY_POLICY_TEXT =\n  ${lines};\n`;
const output = path.join(root, 'constants/appPrivacyPolicyContent.uts');
if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== generated) {
  fs.writeFileSync(output, generated);
}
console.log(`[privacy] bundled ${text.length} characters from ${path.basename(sourcePath)}`);
