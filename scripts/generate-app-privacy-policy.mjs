#!/usr/bin/env node
// 按已核对的官网协议快照与 Android 行为说明生成授权版本，正文由线上网页展示。
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'docs/legal/privacy-source-v2.8.md'), 'utf8');
const disclosure = fs.readFileSync(path.join(root, 'docs/legal/android-clipboard-disclosure.md'), 'utf8');
const sourceVersion = source.match(/\|\s*版本\s*\|\s*V([\d.]+)\s*\|/)?.[1];
if (!sourceVersion) throw new Error('原始隐私协议缺少版本号');
function plain(markdown) {
  return markdown.slice(markdown.indexOf('# '))
    .replace(/\[​\]\([^)]+\)/g, '')
    .replace(/\[([^\]]+)\]\((https?:[^)]+)\)/g, (_, label, url) => url.includes('#') ? label : `${label}（${url}）`)
    .replace(/^\s*#+\s*/gm, '').replace(/\*\*/g, '')
    .replace(/\\([#>|])/g, '$1').replace(/^\|[ \-:|]+\|\s*$/gm, '')
    .replace(/\n{3,}/g, '\n\n').trim();
}
const text = plain(disclosure) + '\n\n' + plain(source);
const fingerprint = crypto.createHash('sha256').update(text).digest('hex');
const version = `${sourceVersion}-android-web-${fingerprint.slice(0, 12)}`;
const generated = '// Generated by scripts/generate-app-privacy-policy.mjs.\n' +
  '// 展示线上协议；网页实质变更后同步 docs/legal 快照，重新构建以触发再次同意。\n' +
  'export const APP_PRIVACY_POLICY_URL = "https://nuwax.com/privacy.html";\n' +
  `export const APP_PRIVACY_POLICY_VERSION = ${JSON.stringify(version)};\n` +
  `export const APP_PRIVACY_POLICY_LABEL = ${JSON.stringify(`V${sourceVersion}`)};\n`;
const output = path.join(root, 'constants/appPrivacyPolicy.uts');
if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== generated) fs.writeFileSync(output, generated);
console.log(`[privacy] ${version}; remote policy; source V${sourceVersion}`);
